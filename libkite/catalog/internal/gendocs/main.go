// Command gendocs compiles Starkite's API reference tables into a Go table
// linked into the catalog and language server.
//
// Run from the repository root:
//
//	go run ./libkite/catalog/internal/gendocs
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"

	"github.com/project-starkite/starkite/libkite/catalog/apidocs"
)

func main() {
	var (
		in    = flag.String("in", "docs/references/api", "directory of API reference markdown")
		out   = flag.String("out", "libkite/catalog/apidocs/table_gen.go", "generated Go file")
		check = flag.Bool("check", false, "verify that generated output matches existing file")
	)
	flag.Parse()

	entries, err := apidocs.ParseDir(*in)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gendocs: reading %s: %v\n", *in, err)
		os.Exit(1)
	}
	if len(entries) == 0 {
		fmt.Fprintf(os.Stderr, "gendocs: no entries parsed from %s\n", *in)
		os.Exit(1)
	}

	sort.Slice(entries, func(i, j int) bool {
		a, b := entries[i], entries[j]
		if a.Module != b.Module {
			return a.Module < b.Module
		}
		if a.Receiver != b.Receiver {
			return a.Receiver < b.Receiver
		}
		return a.Name < b.Name
	})

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by libkite/catalog/internal/gendocs. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package apidocs\n\n")
	fmt.Fprintf(&buf, "// Table holds every documented call and property parsed from\n")
	fmt.Fprintf(&buf, "// docs/references/api. Regenerate with:\n")
	fmt.Fprintf(&buf, "//\n")
	fmt.Fprintf(&buf, "//\tgo run ./libkite/catalog/internal/gendocs\n")
	fmt.Fprintf(&buf, "var Table = []Entry{\n")
	for _, e := range entries {
		fmt.Fprintf(&buf, "\t{Module: %s, Receiver: %s, Name: %s, Signature: %s",
			quote(e.Module), quote(e.Receiver), quote(e.Name), quote(e.Signature))
		if len(e.Params) > 0 {
			fmt.Fprintf(&buf, ", Params: []string{")
			for i, p := range e.Params {
				if i > 0 {
					buf.WriteString(", ")
				}
				buf.WriteString(quote(p))
			}
			buf.WriteString("}")
		}
		if e.Returns != "" {
			fmt.Fprintf(&buf, ", Returns: %s", quote(e.Returns))
		}
		if e.Doc != "" {
			fmt.Fprintf(&buf, ", Doc: %s", quote(e.Doc))
		}
		if e.IsProperty {
			fmt.Fprintf(&buf, ", IsProperty: true")
		}
		buf.WriteString("},\n")
	}
	buf.WriteString("}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "gendocs: formatting output: %v\n", err)
		os.Exit(1)
	}
	if *check {
		existing, err := os.ReadFile(*out)
		if err != nil {
			fmt.Fprintf(os.Stderr, "gendocs: reading existing %s: %v\n", *out, err)
			os.Exit(1)
		}
		if !bytes.Equal(existing, src) {
			fmt.Fprintf(os.Stderr, "gendocs: %s is out of date with %s.\nRun 'make generate-api-docs' to synchronize.\n", *out, *in)
			os.Exit(1)
		}
		fmt.Printf("gendocs: %s is in sync (%d entries)\n", *out, len(entries))
		return
	}

	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "gendocs: writing %s: %v\n", *out, err)
		os.Exit(1)
	}
	fmt.Printf("gendocs: wrote %d entries to %s\n", len(entries), *out)
}

func quote(s string) string {
	return strconv.Quote(s)
}
